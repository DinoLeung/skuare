// Shared by the city map generators, writes the English city names the app shows as string
// resources. Translations go in values-<lang>/ next to them, a city missing there falls back to
// the English name.
package main

import (
	"fmt"
	"os"
	"strings"
)

// composeValuesDir is where Compose Multiplatform reads the base (English) strings from.
const composeValuesDir = "../composeApp/src/commonMain/composeResources/values"

// cityDisplayName is the name the app shows for a city, see writeCityNames.
type cityDisplayName struct {
	id   int
	name string
}

// writeCityNames writes the English names as composeValuesDir/fileName, one string per city named
// keyPrefix + id, e.g. home_tz_30000. The keys are what the app looks the names up by, so they
// must not change. generator and source name the script and CSV in the file's header.
func writeCityNames(fileName, keyPrefix, generator, source string, cities []cityDisplayName) error {
	var xml strings.Builder
	xml.WriteString("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
	fmt.Fprintf(
		&xml,
		"<!--\n\tGenerated by data/%s from data/%s, don't edit by hand.\n"+
			"\tTranslate in values-<lang>/%s, a city missing there shows its English name.\n-->\n",
		generator,
		source,
		fileName,
	)
	xml.WriteString("<resources>\n")
	for _, city := range cities {
		if strings.TrimSpace(city.name) == "" {
			return fmt.Errorf("%s: city %d has no display name", source, city.id)
		}
		fmt.Fprintf(&xml, "\t<string name=\"%s%d\">%s</string>\n", keyPrefix, city.id, xmlText(city.name))
	}
	xml.WriteString("</resources>\n")

	path := composeValuesDir + "/" + fileName
	if err := os.WriteFile(path, []byte(xml.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	fmt.Printf("%d city names have been written to %s\n", len(cities), path)
	return nil
}

// xmlText escapes text for an XML element. Apostrophes stay as they are, Compose resources don't
// unescape \' like Android does.
func xmlText(text string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(text)
}

